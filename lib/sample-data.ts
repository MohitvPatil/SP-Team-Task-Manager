const memberForProject = (projectId: string, userIds: string[]) =>
  userIds.map((userId) => {
    const user = sampleTeamMembers.find((member) => member.id === userId) ?? sampleTeamMembers[0];
    return {
      id: `member-${projectId}-${user.id}`,
      userId: user.id,
      projectId,
      role: user.role,
      position: user.position,
      createdAt: now,
      user,
    };
  });

